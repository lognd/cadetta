"""Write every editor grammar under editors/ from editors/grammar/cadetta.toml.

Run `uv run editors/generate.py` to rewrite the grammars and
`uv run editors/generate.py --check` to fail when a committed grammar is
stale (CI does the latter). The output is deterministic.
"""

from __future__ import annotations

import argparse
import json
import logging
import re
import sys
import tomllib
from pathlib import Path

from pydantic import BaseModel, ConfigDict, ValidationError
from typani import Err, Ok, Result

log = logging.getLogger("cadetta.editors.generate")

EDITORS = Path(__file__).resolve().parent
GRAMMAR = EDITORS / "grammar" / "cadetta.toml"
EMACS_TEMPLATE = EDITORS / "grammar" / "cadetta-mode.el.in"
BANNER = "generated by editors/generate.py, do not edit"
SCOPE = "cadetta"

# role -> (TextMate/Sublime scope, Vim highlight link, Emacs face)
ROLES: dict[str, tuple[str, str, str]] = {
    "declaration": ("storage.type.declaration", "Structure", "font-lock-keyword-face"),
    "control": ("keyword.control", "Statement", "font-lock-keyword-face"),
    "operator": ("keyword.operator.word", "Operator", "font-lock-keyword-face"),
    "constant": ("constant.language", "Boolean", "font-lock-constant-face"),
    "special": ("variable.language", "Identifier", "font-lock-builtin-face"),
    "keyword": ("keyword.control", "Statement", "font-lock-keyword-face"),
    "type": ("support.type", "Type", "font-lock-type-face"),
    "kind": ("support.type.kind", "Type", "font-lock-type-face"),
    "function": ("support.function.builtin", "Function", "font-lock-builtin-face"),
    "pseudo": ("support.constant.citation", "Special", "font-lock-constant-face"),
    "class": ("constant.other.fit-class", "Constant", "font-lock-constant-face"),
    "quantity": ("constant.numeric.quantity", "Number", "font-lock-constant-face"),
    "number": ("constant.numeric", "Number", "font-lock-constant-face"),
    "string": ("string.quoted.double", "String", "font-lock-string-face"),
    "comment": ("comment.line.double-slash", "Comment", "font-lock-comment-face"),
    "doc": ("comment.line.documentation", "SpecialComment", "font-lock-doc-face"),
    "attribute": ("meta.attribute", "PreProc", "font-lock-preprocessor-face"),
    "citation": ("entity.name.tag.citation", "Special", "font-lock-reference-face"),
}


# role -> tree-sitter highlight capture (Helix, Neovim and Zed all resolve these)
TS_CAPTURES: dict[str, str] = {
    "declaration": "keyword",
    "control": "keyword.control",
    "operator": "keyword.operator",
    "constant": "constant.builtin",
    "special": "variable.builtin",
    "type": "type.builtin",
    "kind": "type",
    "function": "function.builtin",
}
TS_PUNCT_BRACKET = ["(", ")", "[", "]", "{", "}"]
TS_PUNCT_DELIM = ["::", "..", ".", ",", ";", ":"]


class Meta(BaseModel):
    """Language identity shared by every editor."""

    model_config = ConfigDict(extra="forbid")
    language: str
    extension: str
    line_comment: str


class Keywords(BaseModel):
    """The reserved words (language.md 2), grouped by highlight role."""

    model_config = ConfigDict(extra="forbid")
    declaration: list[str]
    control: list[str]
    operator: list[str]
    constant: list[str]
    special: list[str]


class Names(BaseModel):
    """Built-in type, kind, function, cite-type and pseudo-citation names."""

    model_config = ConfigDict(extra="forbid")
    types: list[str]
    kinds: list[str]
    functions: list[str]
    cite_types: list[str]
    pseudo_citations: list[str]


class Contextual(BaseModel):
    """A word highlighted only after `lead` + `between` and before `follow`."""

    model_config = ConfigDict(extra="forbid")
    name: str
    lead: str = ""
    between: str = ""
    words: list[str]
    word_regex: bool = False
    follow: str = ""
    role: str
    ts_query: str = ""


class Token(BaseModel):
    """One token pattern in the regex dialect of each engine that needs it."""

    model_config = ConfigDict(extra="forbid")
    pcre: str
    vim: str = ""
    emacs: str = ""
    ts: str = ""


class Grammar(BaseModel):
    """The whole single-source grammar file."""

    model_config = ConfigDict(extra="forbid")
    meta: Meta
    keywords: Keywords
    names: Names
    contextual: list[Contextual]
    tokens: dict[str, Token]


class GrammarError(BaseModel):
    """Why the grammar file could not be loaded."""

    message: str


def load_grammar(path: Path) -> Result[Grammar, GrammarError]:
    """Parse and validate the grammar file; Err on I/O, TOML or schema failure."""
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        log.error("cannot read %s: %s", path, exc)
        return Err(GrammarError(message=f"cannot read {path}: {exc}"))
    try:
        grammar = Grammar.model_validate(data)
    except ValidationError as exc:
        log.error("invalid grammar %s: %s", path, exc)
        return Err(GrammarError(message=f"invalid grammar {path}: {exc}"))
    log.debug("loaded grammar from %s", path)
    return Ok(grammar)


def keyword_groups(g: Grammar) -> list[tuple[str, list[str]]]:
    """The reserved-word groups as (role, words) pairs, in a fixed order."""
    k = g.keywords
    return [
        ("declaration", k.declaration),
        ("control", k.control),
        ("operator", k.operator),
        ("constant", k.constant),
        ("special", k.special),
    ]


def name_groups(g: Grammar) -> list[tuple[str, list[str]]]:
    """The built-in name groups as (role, words) pairs, in a fixed order."""
    n = g.names
    return [("type", n.types), ("kind", n.kinds), ("function", n.functions)]


def lead_role(g: Grammar, lead: str) -> str:
    """The role of a contextual lead keyword (a reserved word)."""
    for role, words in keyword_groups(g):
        if lead in words:
            return role
    raise ValueError(f"contextual lead {lead!r} is not a reserved keyword")


def alternation(words: list[str]) -> str:
    """A pcre alternation of literal words, longest first."""
    return "|".join(sorted(words, key=lambda w: (-len(w), w)))


def ctx_word(c: Contextual) -> str:
    """The pcre fragment matching a contextual's word."""
    return c.words[0] if c.word_regex else alternation(c.words)


def ctx_pcre(g: Grammar, c: Contextual) -> tuple[str, dict[int, str]]:
    """Return (pcre, {capture: role}) for a contextual rule (groups 1 lead, 2 between, 3 word)."""
    lead = f"\\b({c.lead})" if c.lead else "()"
    follow = f"(?={c.follow})" if c.follow else ""
    rx = f"{lead}({c.between})\\b({ctx_word(c)})\\b{follow}"
    caps = {3: c.role}
    if c.lead:
        caps[1] = lead_role(g, c.lead)
    return rx, caps


def scope(role: str) -> str:
    """The full TextMate scope name for a role."""
    return f"{ROLES[role][0]}.{SCOPE}"


def textmate(g: Grammar) -> str:
    """The VS Code / TextMate grammar as JSON text."""

    def rule(match: str, caps: dict[int, str], name: str | None = None) -> dict:
        out: dict = {"match": match}
        if name:
            out["name"] = name
        if caps:
            out["captures"] = {
                str(i): {"name": scope(r)} for i, r in sorted(caps.items())
            }
        return out

    t = g.tokens
    patterns: list[dict] = [
        {"match": r"///.*$", "name": scope("doc")},
        {"match": r"//.*$", "name": scope("comment")},
        {"match": t["string"].pcre, "name": scope("string")},
        {"match": t["attribute"].pcre, "name": scope("attribute")},
    ]
    patterns += [rule(*ctx_pcre(g, c)) for c in g.contextual]
    pseudo = alternation(g.names.pseudo_citations)
    patterns.append(
        {
            "match": f'@(?:{pseudo})\\b(?::"(?:\\\\.|[^"\\\\])*")?',
            "name": scope("pseudo"),
        }
    )
    patterns.append({"match": t["citation"].pcre, "name": scope("citation")})
    patterns.append(
        rule(
            f"({t['quantity'].pcre})([ \\t]+)({t['class'].pcre})",
            {1: "quantity", 3: "class"},
        )
    )
    patterns.append({"match": t["quantity"].pcre, "name": scope("quantity")})
    patterns.append({"match": t["number"].pcre, "name": scope("number")})
    for role, words in keyword_groups(g) + name_groups(g):
        patterns.append(
            {"match": f"\\b(?:{alternation(words)})\\b", "name": scope(role)}
        )
    doc = {
        "comment": BANNER,
        "name": "Cadetta",
        "scopeName": f"source.{SCOPE}",
        "patterns": patterns,
    }
    return json.dumps(doc, indent=2, ensure_ascii=True) + "\n"


def yq(text: str) -> str:
    """Quote text as a YAML single-quoted scalar."""
    return "'" + text.replace("'", "''") + "'"


def sublime(g: Grammar) -> str:
    """The Sublime Text .sublime-syntax text."""
    t = g.tokens

    def item(
        match: str, name: str | None = None, caps: dict[int, str] | None = None
    ) -> list[str]:
        lines = [f"    - match: {yq(match)}"]
        if name:
            lines.append(f"      scope: {name}")
        if caps:
            lines.append("      captures:")
            lines += [f"        {i}: {scope(r)}" for i, r in sorted(caps.items())]
        return lines

    pseudo = alternation(g.names.pseudo_citations)
    out = [
        "%YAML 1.2",
        f"# {BANNER}",
        "---",
        "name: Cadetta",
        f"file_extensions: [{g.meta.extension}]",
        f"scope: source.{SCOPE}",
        "contexts:",
        "  main:",
    ]
    out += item(r"///.*$", scope("doc"))
    out += item(r"//.*$", scope("comment"))
    out += item(t["string"].pcre, scope("string"))
    out += item(t["attribute"].pcre, scope("attribute"))
    for c in g.contextual:
        rx, caps = ctx_pcre(g, c)
        out += item(rx, None, caps)
    out += item(f'@(?:{pseudo})\\b(?::"(?:\\\\.|[^"\\\\])*")?', scope("pseudo"))
    out += item(t["citation"].pcre, scope("citation"))
    out += item(
        f"({t['quantity'].pcre})([ \\t]+)({t['class'].pcre})",
        None,
        {1: "quantity", 3: "class"},
    )
    out += item(t["quantity"].pcre, scope("quantity"))
    out += item(t["number"].pcre, scope("number"))
    for role, words in keyword_groups(g) + name_groups(g):
        out += item(f"\\b(?:{alternation(words)})\\b", scope(role))
    return "\n".join(out) + "\n"


def vim_frag(frag: str) -> str:
    """Convert a portable pcre fragment to Vim very-magic syntax."""
    frag = frag.replace("(?:", "(")
    return re.sub(r"(?<!\\)=", r"\\=", frag)


def vim_ctx(c: Contextual) -> str:
    """The Vim very-magic pattern for a contextual rule (lookbehind on lead + between)."""
    word = vim_frag(ctx_word(c))
    pre = (f"<{c.lead}" if c.lead else "") + vim_frag(c.between)
    follow = f"({vim_frag(c.follow)})@=" if c.follow else ""
    behind = f"({pre})@<=" if pre else "<"
    return f"\\v{behind}({word})>{follow}"


def vim(g: Grammar) -> str:
    """The Vim/Neovim syntax file text."""
    t = g.tokens
    link = {role: f"cadetta{role.capitalize()}" for role in ROLES}
    out = [
        f'" {BANNER}',
        "if exists('b:current_syntax')",
        "  finish",
        "endif",
        "syntax case match",
        "",
    ]
    for role, words in keyword_groups(g) + name_groups(g):
        out.append(f"syntax keyword {link[role]} {' '.join(words)}")
    out.append("")

    def match(role: str, pat: str, extra: str = "") -> None:
        pat = re.sub(r"(?<![\\%])\(", "%(", pat)  # non-capturing: Vim's NFA caps groups
        out.append(f"syntax match {link[role]} ~{pat}~{extra}")

    match("number", "\\v" + t["number"].vim)
    match("quantity", "\\v" + t["quantity"].vim)
    match("class", f"\\v({t['quantity'].vim}[ \\t]+)@<=" + t["class"].vim, "")
    for c in g.contextual:
        match(c.role, vim_ctx(c))
    match("citation", "\\v" + t["citation"].vim.replace("@", "\\@", 1))
    match(
        "pseudo",
        f'\\v\\@({alternation(g.names.pseudo_citations)})>(:"(\\\\.|[^"\\\\])*")?',
    )
    match("attribute", "\\v" + t["attribute"].vim)
    match("string", "\\v" + t["string"].vim)
    match("comment", "//.*$")
    match("doc", "///.*$")
    out.append("")
    for role in ROLES:
        out.append(f"highlight default link {link[role]} {ROLES[role][1]}")
    out += ["", "let b:current_syntax = 'cadetta'"]
    return "\n".join(out) + "\n"


def to_emacs(frag: str) -> str:
    """Convert a portable pcre fragment (class-aware) to an Emacs regexp."""
    out: list[str] = []
    in_class = False
    i = 0
    while i < len(frag):
        ch = frag[i]
        if in_class:
            if ch == "\\" and frag[i + 1 : i + 2] == "t":
                out.append("\t")
                i += 1
            else:
                out.append(ch)
                in_class = ch != "]"
        elif ch == "\\" and i + 1 < len(frag):
            nxt = frag[i + 1]
            out.append("\t" if nxt == "t" else ch + nxt)
            i += 1
        elif ch == "[":
            out.append(ch)
            in_class = True
        elif ch in "(){}|":
            out.append("\\" + ch)
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def el(text: str) -> str:
    """Quote text as an elisp string literal."""
    esc = text.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")
    return f'"{esc}"'


def emacs(g: Grammar) -> str:
    """The Emacs major mode text, from the template with the lists filled in."""
    t = g.tokens
    consts = []
    for role, words in keyword_groups(g) + name_groups(g):
        body = " ".join(el(w) for w in words)
        consts.append(f"(defconst cadetta--{role}-names '({body}))")
    consts.append(
        "(defconst cadetta--pseudo-citations '("
        + " ".join(el(w) for w in g.names.pseudo_citations)
        + "))"
    )
    ctx = []
    for c in g.contextual:
        pre = (f"\\_<{c.lead}" if c.lead else "") + to_emacs(c.between)
        word = to_emacs(ctx_word(c))
        follow = to_emacs(c.follow)
        rx = (
            f"{pre}\\({word}\\)\\_>{follow}" if pre else f"\\_<\\({word}\\)\\_>{follow}"
        )
        ctx.append(f"'({el(rx)} 1 '{ROLES[c.role][2]})")
    quant_class = f"\\(?:{t['quantity'].emacs}\\)[ \t]+\\({t['class'].emacs}\\)"
    rules = [f"'({el(quant_class)} 1 '{ROLES['class'][2]})"]
    rules.append(f"'({el(t['quantity'].emacs)} 0 '{ROLES['quantity'][2]})")
    rules.append(f"'({el(t['number'].emacs)} 0 '{ROLES['number'][2]})")
    rules.append(f"'({el(t['attribute'].emacs)} 0 '{ROLES['attribute'][2]} t)")
    rules.append(f"'({el(t['citation'].emacs)} 0 '{ROLES['citation'][2]})")
    text = EMACS_TEMPLATE.read_text(encoding="utf-8")
    for key, value in {
        "CONSTS": "\n".join(consts),
        "CONTEXTUAL": "\n    ".join(ctx),
        "TOKENS": "\n    ".join(rules),
    }.items():
        text = text.replace(f"@@{key}@@", value)
    return text


def js_regex(pattern: str) -> str:
    """A JavaScript regex literal for a pattern, escaping bare slashes."""
    return "/" + re.sub(r"(?<!\\)/", r"\\/", pattern) + "/"


def ts_token(t: Token) -> str:
    """The tree-sitter (Rust regex dialect) pattern of a token."""
    return t.ts or t.pcre


def js_str(text: str) -> str:
    """A single-quoted JavaScript string literal."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def ts_keywords(g: Grammar) -> list[str]:
    """Every reserved word once, in a fixed order."""
    seen: dict[str, None] = {}
    for _, words in keyword_groups(g):
        seen.update(dict.fromkeys(words))
    return list(seen)


def tree_sitter_grammar(g: Grammar) -> str:
    """The tree-sitter grammar.js: a flat token stream, so it never yields ERROR nodes."""
    t = g.tokens
    pseudo = alternation(g.names.pseudo_citations)
    locator = t["string"].pcre
    literals = TS_PUNCT_BRACKET + TS_PUNCT_DELIM + ts_keywords(g)
    lit = ",\n      ".join(js_str(x) for x in literals)
    return f"""// {BANNER}
// A lexical grammar: Cadetta source is a stream of tokens, highlighted by
// queries/highlights.scm. Every character lexes, so no input has ERROR nodes.
module.exports = grammar({{
  name: '{g.meta.language}',

  word: $ => $.identifier,

  extras: _ => [/\s+/],

  rules: {{
    source_file: $ => repeat($._item),

    _item: $ => choice(
      $.doc_comment,
      $.comment,
      $.string,
      $.attribute,
      $.pseudo_citation,
      $.citation,
      $.quantity,
      $.number,
      $.operator,
      $.identifier,
      $.unknown,
      {lit},
    ),

    doc_comment: _ => token(prec(1, /\/\/\/.*/)),
    comment: _ => token(/\/\/.*/),
    string: _ => token({js_regex(t["string"].pcre)}),
    attribute: _ => token({js_regex(ts_token(t["attribute"]))}),
    pseudo_citation: _ => token(prec(1, {js_regex(f"@(?:{pseudo})(?::{locator})?")})),
    citation: _ => token({js_regex(ts_token(t["citation"]))}),
    quantity: _ => token({js_regex(ts_token(t["quantity"]))}),
    number: _ => token({js_regex(ts_token(t["number"]))}),
    operator: _ => token(/[-+*\/=<>!^%&|~?]+/),
    identifier: _ => /[A-Za-z_][A-Za-z0-9_]*/,
    unknown: _ => token(prec(-1, /[^\s]/)),
  }},
}});
"""


def tree_sitter_highlights(g: Grammar) -> str:
    """The tree-sitter queries/highlights.scm text."""
    quote = lambda ws: " ".join(f'"{w}"' for w in ws)  # noqa: E731
    out = [
        f"; {BANNER}",
        "(doc_comment) @comment.documentation",
        "(comment) @comment",
        "(string) @string",
        "(attribute) @attribute",
        "(pseudo_citation) @string.special",
        "(citation) @label",
        "(quantity) @number @constant.numeric",
        "(number) @number @constant.numeric",
        "(operator) @operator",
        f"[{quote(TS_PUNCT_BRACKET)}] @punctuation.bracket",
        f"[{quote(TS_PUNCT_DELIM)}] @punctuation.delimiter",
        "",
    ]
    for role, words in keyword_groups(g):
        out.append(f"[{quote(words)}] @{TS_CAPTURES[role]}")
    out.append("")
    for role, words in name_groups(g):
        cap = TS_CAPTURES[role]
        out.append(f"((identifier) @{cap} (#any-of? @{cap} {quote(words)}))")
    out += ["", "; contextual words and ISO 286 classes"]
    for c in g.contextual:
        if c.ts_query:
            out.append(c.ts_query.replace("{words}", quote(c.words)))
    out.append(
        '((quantity) . (identifier) @constant (#match? @constant "^[A-Za-z]{1,2}[0-9]{1,2}$"))'
    )
    return "\n".join(out) + "\n"


def outputs(g: Grammar) -> dict[Path, str]:
    """Every generated file path mapped to its content."""
    return {
        EDITORS / "vscode" / "syntaxes" / "cadetta.tmLanguage.json": textmate(g),
        EDITORS / "sublime" / "Cadetta.sublime-syntax": sublime(g),
        EDITORS / "vim" / "syntax" / "cadetta.vim": vim(g),
        EDITORS / "emacs" / "cadetta-mode.el": emacs(g),
        EDITORS / "tree-sitter" / "grammar.js": tree_sitter_grammar(g),
        EDITORS / "tree-sitter" / "queries" / "highlights.scm": tree_sitter_highlights(g),
    }


def run(check: bool) -> Result[int, GrammarError]:
    """Write (or with `check`, verify) every grammar; Ok(number of stale files)."""
    loaded = load_grammar(GRAMMAR)
    if isinstance(loaded, Err):
        return loaded
    stale = 0
    for path, text in outputs(loaded.unwrap()).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        rel = path.relative_to(EDITORS.parent)
        if current == text:
            log.debug("up to date: %s", rel)
        elif check:
            log.error("stale: %s (run: uv run editors/generate.py)", rel)
            stale += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            log.info("wrote %s", rel)
    return Ok(stale)


def main(argv: list[str] | None = None) -> int:
    """Entry point: exit 0 when written or current, 1 when stale or the grammar is bad."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if a grammar is stale"
    )
    args = parser.parse_args(argv)
    logging.basicConfig(
        level=logging.INFO, format="%(levelname)s %(message)s", stream=sys.stderr
    )
    result = run(args.check)
    match result:
        case Ok(stale):
            return 1 if stale else 0
        case Err(error):
            log.error("%s", error.message)
            return 1
    return 1


if __name__ == "__main__":
    sys.exit(main())
